import { describe, expect, it } from 'vitest';
import { existsSync } from 'fs';
import { sportsData } from '../teams.js';

const all = Object.entries(sportsData).flatMap(([league, d]) => d.teams.map((t) => ({ ...t, league })));

describe('team data (generated by scripts/gen-teams.mjs)', () => {
  it('has the leagues the app offers', () => {
    expect(Object.keys(sportsData)).toEqual(
      expect.arrayContaining(['nfl', 'nba', 'nhl', 'mlb', 'mls', 'cfl', 'epl', 'laliga', 'bundesliga', 'seriea', 'ligue1'])
    );
    for (const d of Object.values(sportsData)) {
      expect(d.name).toBeTruthy();
      expect(d.teams.length).toBeGreaterThan(5);
    }
  });

  it('team ids are unique across every league (share links carry only the id)', () => {
    const ids = all.map((t) => t.id);
    expect(new Set(ids).size).toBe(ids.length);
    for (const id of ids) expect(id).toMatch(/^[a-z0-9_]{1,40}$/);
  });

  it('every team is fully described', () => {
    for (const t of all) {
      expect(t.name, t.id).toBeTruthy();
      expect(t.short, t.id).toMatch(/^[A-Z0-9]{2,4}$/);
      expect(t.city, t.id).toBeTruthy();
      expect(['champs', 'powerhouse', 'heartbreak', 'standard'], t.id).toContain(t.status);
      for (const k of ['primary', 'secondary', 'text']) expect(t[k], `${t.id}.${k}`).toMatch(/^#[0-9A-Fa-f]{6}$/);
      expect(t.logo, t.id).toMatch(/^(https:\/\/|\/logos\/)/);
      if (t.founded !== undefined) expect(t.founded, t.id).toBeGreaterThan(1800);
    }
  });

  it('locally hosted logos exist in public/', () => {
    const local = all.filter((t) => t.logo.startsWith('/'));
    for (const t of local) expect(existsSync(new URL(`../public${t.logo}`, import.meta.url)), t.logo).toBe(true);
  });
});
